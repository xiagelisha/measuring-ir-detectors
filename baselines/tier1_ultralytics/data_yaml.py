"""为 ultralytics 训练准备数据目录 + data.yaml。

ultralytics 默认在 images/ 同级找 labels/, 而本项目原始结构为:
  data/OilData/<stem>.JPG       (images)
  data/OilLabels/<stem>.txt     (yolo labels)

解决方案: 把 splits 引导的子集 *硬拷贝* 到 ultralytics 期望的标准目录:
  <root>/results_v2/baselines/tier1/ultralytics_data/
    images/{train,val,test}/<stem>.JPG
    labels/{train,val,test}/<stem>.txt

并写 data.yaml 指向该目录。

幂等: 已存在的目标文件跳过 copy。
"""
from __future__ import annotations

import shutil
from pathlib import Path
from typing import List, Sequence


def _read_basenames(txt_path: Path) -> List[str]:
    stems: List[str] = []
    for raw in txt_path.read_text(encoding="utf-8").splitlines():
        s = raw.strip()
        if not s or s.startswith("#"):
            continue
        stems.append(Path(s).stem)
    return stems


def _materialize_split(
    stems: Sequence[str],
    src_img_dir: Path,
    src_lbl_dir: Path,
    dst_img_dir: Path,
    dst_lbl_dir: Path,
) -> int:
    dst_img_dir.mkdir(parents=True, exist_ok=True)
    dst_lbl_dir.mkdir(parents=True, exist_ok=True)
    n = 0
    for stem in stems:
        # find image (.JPG / .jpg)
        src_img = None
        for ext in (".JPG", ".jpg", ".jpeg", ".png", ".bmp"):
            cand = src_img_dir / f"{stem}{ext}"
            if cand.is_file():
                src_img = cand
                break
        if src_img is None:
            raise FileNotFoundError(f"image not found for stem '{stem}' in {src_img_dir}")
        src_lbl = src_lbl_dir / f"{stem}.txt"
        if not src_lbl.is_file():
            raise FileNotFoundError(f"label not found: {src_lbl}")

        dst_img = dst_img_dir / src_img.name
        dst_lbl = dst_lbl_dir / src_lbl.name
        if not dst_img.is_file() or dst_img.stat().st_size != src_img.stat().st_size:
            shutil.copyfile(src_img, dst_img)
        if not dst_lbl.is_file() or dst_lbl.stat().st_size != src_lbl.stat().st_size:
            shutil.copyfile(src_lbl, dst_lbl)
        n += 1
    return n


def build_data_yaml(
    splits_dir: Path,
    output_yaml_path: Path,
    project_root: Path,
    names: Sequence[str] = ("Water", "Oil"),
    ultralytics_data_dir: Path = None,
) -> Path:
    """生成 ultralytics 期望的数据目录 + data.yaml。

    Args:
        splits_dir: data/splits/<split_name>/  含 train.txt val.txt test.txt
        output_yaml_path: 写入的 data.yaml 路径
        project_root: 项目根
        names: 类别名 (顺序与 label class_id 对应)
        ultralytics_data_dir: 标准目录根, 默认 results_v2/baselines/tier1/ultralytics_data

    Returns:
        output_yaml_path
    """
    splits_dir = Path(splits_dir)
    output_yaml_path = Path(output_yaml_path)
    project_root = Path(project_root)
    if ultralytics_data_dir is None:
        ultralytics_data_dir = project_root / "results_v2" / "baselines" / "tier1" / "ultralytics_data"
    ultralytics_data_dir = Path(ultralytics_data_dir)

    src_img_dir = project_root / "data" / "OilData"
    src_lbl_dir = project_root / "data" / "OilLabels"
    if not src_img_dir.is_dir():
        raise FileNotFoundError(f"OilData not found: {src_img_dir}")
    if not src_lbl_dir.is_dir():
        raise FileNotFoundError(f"OilLabels not found: {src_lbl_dir}")

    counts = {}
    for split in ("train", "val", "test"):
        txt = splits_dir / f"{split}.txt"
        if not txt.is_file():
            raise FileNotFoundError(f"split file missing: {txt}")
        stems = _read_basenames(txt)
        dst_img = ultralytics_data_dir / "images" / split
        dst_lbl = ultralytics_data_dir / "labels" / split
        n = _materialize_split(stems, src_img_dir, src_lbl_dir, dst_img, dst_lbl)
        counts[split] = n

    # write data.yaml
    names_str = "\n".join([f"  {i}: {name}" for i, name in enumerate(names)])
    yaml_text = (
        f"# Generated by data_yaml.build_data_yaml\n"
        f"path: {ultralytics_data_dir.as_posix()}\n"
        f"train: images/train\n"
        f"val: images/val\n"
        f"test: images/test\n"
        f"names:\n{names_str}\n"
    )
    output_yaml_path.parent.mkdir(parents=True, exist_ok=True)
    output_yaml_path.write_text(yaml_text, encoding="utf-8")

    print(f"[data_yaml] train/val/test = {counts['train']}/{counts['val']}/{counts['test']}")
    print(f"[data_yaml] data root      = {ultralytics_data_dir}")
    print(f"[data_yaml] yaml           = {output_yaml_path}")

    # 验证 ultralytics 能加载
    try:
        from ultralytics.data.utils import check_det_dataset
        info = check_det_dataset(str(output_yaml_path))
        n_classes = len(info.get("names", {}))
        print(f"[data_yaml] ultralytics check_det_dataset OK, names={info.get('names')}")
        if n_classes != len(names):
            raise RuntimeError(f"class count mismatch: got {n_classes}, expected {len(names)}")
    except Exception as e:
        print(f"[data_yaml] WARN: check_det_dataset failed: {e}")

    return output_yaml_path


